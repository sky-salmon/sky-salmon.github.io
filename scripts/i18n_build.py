"""Build assets/js/i18n-dict.js for the translated pages (card editor and catalogue).

Keys are the Traditional Chinese source strings themselves:
  - visible text and placeholder / aria-label / title / alt / meta-description attributes in card.html, wardrobe.html
  - the first argument of every t('...') call in assets/js/{card,card-data,site,i18n,cloud,wardrobe}.js
English comes from i18n/en.json (hand-written, key -> English). Simplified Chinese is generated with OpenCC
(tw2sp: Taiwan phrasing -> mainland phrasing), with fixes from i18n/zh-Hans.overrides.json.

usage: python scripts/i18n_build.py            # build, report missing English keys
       python scripts/i18n_build.py --keys     # just print the keys (for writing translations)
needs: pip install opencc-python-reimplemented
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CJK = re.compile(r"[㐀-鿿]")


def html_keys() -> list[str]:
    s = "".join((ROOT / f).read_text(encoding="utf-8") for f in ("card.html", "wardrobe.html"))
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<(script|style)\b.*?</\1>", "", s, flags=re.S)
    keys = [t.strip() for t in re.findall(r">([^<>]*)<", s)]
    keys += [v for _, v in re.findall(r'\s(placeholder|aria-label|title|alt|content)="([^"]*)"', s)]
    return [k for k in keys if CJK.search(k)]


def js_keys() -> list[str]:
    keys = []
    for f in ("card.js", "card-value.js", "card-challenge.js", "card-data.js", "site.js", "i18n.js", "cloud.js", "wardrobe.js", "access.js"):
        s = (ROOT / "assets" / "js" / f).read_text(encoding="utf-8")
        keys += [m.replace("\\'", "'") for m in re.findall(r"\bt\('((?:[^'\\]|\\.)*)'", s)]
    return [k for k in keys if CJK.search(k)]


def main():
    keys = list(dict.fromkeys(html_keys() + js_keys()))
    if "--keys" in sys.argv:
        print(json.dumps(keys, ensure_ascii=False, indent=0))
        return
    en = json.loads((ROOT / "i18n" / "en.json").read_text(encoding="utf-8"))
    over_path = ROOT / "i18n" / "zh-Hans.overrides.json"
    over = json.loads(over_path.read_text(encoding="utf-8")) if over_path.exists() else {}
    from opencc import OpenCC
    cc = OpenCC("tw2sp")
    hans = {k: over.get(k, cc.convert(k)) for k in keys}
    missing = [k for k in keys if k not in en]
    unused = [k for k in en if k not in keys]
    out = {"en": {k: en[k] for k in keys if k in en}, "zh-Hans": {k: v for k, v in hans.items() if v != k}}
    (ROOT / "assets" / "js" / "i18n-dict.js").write_text(
        "/* generated by scripts/i18n_build.py from i18n/en.json (+ OpenCC for zh-Hans); do not edit by hand */\n"
        "window.I18N_DICT = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print(f"{len(keys)} keys; en {len(out['en'])}; zh-Hans {len(out['zh-Hans'])}")
    if missing:
        print("missing English:", json.dumps(missing, ensure_ascii=False))
    if unused:
        print("unused English entries:", json.dumps(unused, ensure_ascii=False))
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
