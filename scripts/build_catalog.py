"""Build assets/js/seasons-data.js from data/seasons.json, and check the three data files.

data/ is the single source for hand-maintained catalogue data (seasons, item corrections, paid packs).
The icon tree and assets/icons/icons.csv are produced from it by sky-fish-mod/tools/sky_icon_extract.py --flat.
Simplified Chinese season names are filled with OpenCC (tw2sp) when zh_hans is empty.
usage: python scripts/build_catalog.py      (needs: pip install opencc-python-reimplemented)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
GROUPS = {"pass", "top", "shoes", "outfit", "mask", "face", "neck", "hair", "head", "ear", "cape", "prop"}
STATUS = {"confirmed", "game-only", "wiki-only"}


def main():
    seasons = json.loads((DATA / "seasons.json").read_text(encoding="utf-8"))["seasons"]
    items = json.loads((DATA / "items.json").read_text(encoding="utf-8"))["items"]
    packs = json.loads((DATA / "packs.json").read_text(encoding="utf-8"))["packs"]

    errors = []
    codes = [s["code"] for s in seasons]
    if len(codes) != len(set(codes)):
        errors.append("duplicate season codes")
    for s in seasons:
        if not re.fullmatch(r"\d\d", s["code"]) or not s.get("zh") or not s.get("en"):
            errors.append(f"season {s.get('code')}: needs a two-digit code, zh and en")
    for name, o in items.items():
        if "group" in o and o["group"] not in GROUPS:
            errors.append(f"item {name}: unknown group {o['group']}")
        if o.get("season") and o["season"] not in codes:
            errors.append(f"item {name}: unknown season {o['season']}")
    ids = [p["id"] for p in packs]
    if len(ids) != len(set(ids)):
        errors.append("duplicate pack ids")
    for p in packs:
        if p.get("status") not in STATUS:
            errors.append(f"pack {p['id']}: status must be one of {sorted(STATUS)}")
        if p.get("usd") is not None and not isinstance(p["usd"], (int, float)):
            errors.append(f"pack {p['id']}: usd must be a number or null")
        if not p.get("items"):
            errors.append(f"pack {p['id']}: no items")
    if errors:
        print("\n".join(errors))
        sys.exit(1)

    from opencc import OpenCC
    cc = OpenCC("tw2sp")
    out = [{"code": s["code"], "zh": s["zh"], "zh_hans": s.get("zh_hans") or cc.convert(s["zh"]), "en": s["en"],
            "start": s.get("start", ""), "end": s.get("end", ""), "note": s.get("note", "")} for s in seasons]
    (ROOT / "assets" / "js" / "seasons-data.js").write_text(
        "/* generated by scripts/build_catalog.py from data/seasons.json; do not edit by hand */\n"
        "window.SKY_SEASONS = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print(f"{len(seasons)} seasons, {len(items)} item corrections, {len(packs)} packs: ok")


if __name__ == "__main__":
    main()
